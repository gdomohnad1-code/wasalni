type Key = keyof typeof dict["ar"];

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: Key) => string;
  dir: "rtl" | "ltr";
  locale: string;
}

const Ctx = createContext<I18nCtx | null>(null);

function getInitialLang(): Lang {
  if (typeof window === "undefined") return "ar";
  const stored = localStorage.getItem("app_lang");
  return stored === "en" ? "en" : "ar";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");

  useEffect(() => {
    setLangState(getInitialLang());
  }, []);

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("app_lang", l);
  }, []);

  const t = useCallback((k: Key) => (dict[lang] as Record<string, string>)[k] ?? (dict.ar as Record<string, string>)[k] ?? k, [lang]);

  const value = useMemo(
    () => ({
      lang,
      setLang,
      t,
      dir: (lang === "ar" ? "rtl" : "ltr") as "rtl" | "ltr",
      locale: lang === "ar" ? "ar-EG" : "en-US",
    }),
    [lang, setLang, t],
  );

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const c = useContext(Ctx);
  if (!c) throw new Error("useI18n must be used within I18nProvider");
  return c;
}
